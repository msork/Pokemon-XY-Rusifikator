def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--batch", type=Path, default=ROOT / "build/milestone-3d/early-game-batch.jsonl")
    parser.add_argument("--output", type=Path, default=ROOT / "translations/early-game.jsonl")
    args = parser.parse_args()
    rows = {row["record_id"]: row for row in (json.loads(line) for line in args.batch.read_text(encoding="utf-8").splitlines() if line.strip())}
    output = []
    for record_id, translated_text in sorted(DRAFTS.items()):
        if record_id not in rows:
            raise ValueError(f"Source record missing from local batch: {record_id}")
        row = dict(rows[record_id])
        expected = sum("text" in segment for segment in row["source_segments"])
        if len(translated_text) != expected:
            raise ValueError(f"Expected {expected} text segments for {record_id}, got {len(translated_text)}")
        iterator = iter(translated_text)
        row["translation_segments"] = [({"text": next(iterator)} if "text" in segment else {"control_words": list(segment["control_words"])})
                                        for segment in row["source_segments"]]
        row["status"] = "draft"
        row["review_note"] = "Project-authored draft; requires human linguistic review and owner runtime testing."
        row["context"] = "opening home/neighbor dialogue" if "/8/2:" in record_id else "general first-battle UI templates"
        row.pop("source_text", None)
        row.pop("source_segments", None)
        row.pop("occurrences", None)
        output.append(row)
    write_jsonl(args.output.resolve(), output)
    print(json.dumps({"records": len(output), "statuses": ["draft"], "output": args.output.resolve().as_posix()}, ensure_ascii=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
